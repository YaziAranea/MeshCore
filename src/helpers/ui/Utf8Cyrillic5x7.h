static inline bool meshcoreCp1251Codepoint(uint8_t c, uint16_t* codepoint) {
  if (c >= 0xC0 && c <= 0xDF) {
    *codepoint = 0x0410 + (c - 0xC0);
    return true;
  }
  if (c >= 0xE0 && c <= 0xFF) {
    *codepoint = 0x0430 + (c - 0xE0);
    return true;
  }
  if (c == 0xA8) {
    *codepoint = 0x0401;
    return true;
  }
  if (c == 0xB8) {
    *codepoint = 0x0451;
    return true;
  }
  return false;
}

static inline bool meshcoreAppendUtf8Codepoint(char* dest, size_t dest_size, size_t& j, uint16_t codepoint) {
  if (codepoint < 0x80) {
    if (j + 1 >= dest_size) return false;
    dest[j++] = (char) codepoint;
    return true;
  }
  if (codepoint < 0x800) {
    if (j + 2 >= dest_size) return false;
    dest[j++] = (char) (0xC0 | (codepoint >> 6));
    dest[j++] = (char) (0x80 | (codepoint & 0x3F));
    return true;
  }
  if (j + 3 >= dest_size) return false;
  dest[j++] = (char) (0xE0 | (codepoint >> 12));
  dest[j++] = (char) (0x80 | ((codepoint >> 6) & 0x3F));
  dest[j++] = (char) (0x80 | (codepoint & 0x3F));
  return true;
}

