static inline const char* meshcoreEmojiAlias(const char* src, size_t* consumed) {
  for (size_t i = 0; i < sizeof(meshcore_emoji_aliases) / sizeof(meshcore_emoji_aliases[0]); i++) {
    size_t len = strlen(meshcore_emoji_aliases[i].utf8);
    if (strncmp(src, meshcore_emoji_aliases[i].utf8, len) == 0) {
      *consumed = len;
      return meshcore_emoji_aliases[i].ascii;
    }
  }
  return NULL;
}

static inline bool meshcoreAppendAscii(char* dest, size_t dest_size, size_t& j, const char* text) {
  while (text && *text) {
    if (j >= dest_size - 1) return false;
    dest[j++] = *text++;
  }
  return true;
}

static inline void meshcoreCopySupportedUtf8(char* dest, const char* src, size_t dest_size) {
  if (dest_size == 0) return;
  size_t j = 0;
  while (src && *src && j < dest_size - 1) {
    size_t consumed = 0;
    const char* alias = meshcoreEmojiAlias(src, &consumed);
    if (alias) {
      if (!meshcoreAppendAscii(dest, dest_size, j, alias)) break;
      src += consumed;
      continue;
    }

    const char* start = src;
    uint8_t first = (uint8_t)*src;
    uint16_t cp = meshcoreReadUtf8Codepoint(src);
    size_t len = src - start;
    if (first >= 0x80 && cp == '?') {
      uint16_t cp1251;
      if (len == 1 && meshcoreCp1251Codepoint(first, &cp1251)) {
        src = start + 1;
        if (!meshcoreAppendUtf8Codepoint(dest, dest_size, j, cp1251)) break;
        continue;
      }
      if (strncmp(start, "\xEF\xB8\x8F", len) == 0 || strncmp(start, "\xE2\x80\x8D", len) == 0) {
        continue;
      }
      if (!meshcoreAppendAscii(dest, dest_size, j, "*")) break;
      continue;
    }
    bool supported = (cp >= 32 && cp <= 126) || cp == '\n' || cp == '\r' || meshcoreCyrillicGlyph5x7(cp) != NULL;
    if (!supported) {
      dest[j++] = '*';
      continue;
    }
    if (j + len >= dest_size) break;
    memcpy(&dest[j], start, len);
    j += len;
  }
  dest[j] = 0;
}
