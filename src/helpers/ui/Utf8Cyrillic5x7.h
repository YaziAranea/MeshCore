static inline uint16_t meshcoreReadUtf8Codepoint(const char*& str) {
  uint8_t c = (uint8_t)*str++;
  if (c < 0x80) return c;

  if ((c & 0xE0) == 0xC0 && (*str & 0xC0) == 0x80) {
    uint16_t cp = ((uint16_t)(c & 0x1F) << 6) | ((uint8_t)*str++ & 0x3F);
    return cp;
  }

  if ((c & 0xF0) == 0xE0) {
    for (int i = 0; i < 2 && (*str & 0xC0) == 0x80; i++) str++;
  } else if ((c & 0xF8) == 0xF0) {
    for (int i = 0; i < 3 && (*str & 0xC0) == 0x80; i++) str++;
  } else {
    while ((*str & 0xC0) == 0x80) str++;
  }
  return '?';
}

static inline const uint8_t* meshcoreCyrillicGlyph5x7(uint16_t codepoint) {
  if (codepoint == 0x0451) return meshcore_cyrillic_lower_5x7[5];
  if (codepoint >= 0x0430 && codepoint <= 0x044F) {
    return meshcore_cyrillic_lower_5x7[codepoint - 0x0430];
  }
  if (codepoint == 0x0401) return meshcore_cyrillic_5x7[5];
  if (codepoint >= 0x0410 && codepoint <= 0x042F) {
    return meshcore_cyrillic_5x7[codepoint - 0x0410];
  }
  return NULL;
}

